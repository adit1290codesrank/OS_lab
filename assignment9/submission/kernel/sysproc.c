int
sys_exit(void)
{
  exit();
  return 0;  // not reached
}

int
sys_wait(void)
{
  return wait();
}

int
sys_kill(void)
{
  int pid;

  if(argint(0, &pid) < 0)
    return -1;
  return kill(pid);
}

int
sys_getpid(void)
{
  return myproc()->pid;
}

int
sys_sbrk(void)
{
  int addr;
  int n;

  if(argint(0, &n) < 0)
    return -1;
  addr = myproc()->sz;
  if(n > 0){
    // A9 Q2: lazy allocation - only grow sz, frames are allocated on first access
    if((uint)addr + n >= KERNBASE || (uint)addr + n < (uint)addr)
      return -1;
    myproc()->sz += n;
  } else if(growproc(n) < 0)   // shrinking still frees the pages via deallocuvm
    return -1;
  return addr;
}

int
sys_sleep(void)
{
  int n;
  uint ticks0;

  if(argint(0, &n) < 0)
    return -1;
  acquire(&tickslock);
  ticks0 = ticks;
  while(ticks - ticks0 < n){
    if(myproc()->killed){
      release(&tickslock);
      return -1;
    }
    sleep(&ticks, &tickslock);
  }
  release(&tickslock);
  return 0;
}

// return how many clock tick interrupts have occurred
// since start.
int
sys_uptime(void)
{
  uint xticks;

  acquire(&tickslock);
  xticks = ticks;
  release(&tickslock);
  return xticks;
}

// A9 Q1: print the calling process's page table
int
sys_vmprint(void)
{
  vmprint(myproc()->pgdir);
  return 0;
}

// A9 Q2: return the number of page faults handled for the calling process
int
sys_getfaults(void)
{
  return myproc()->faults;
}
